def env(name, default=None):
    """Return an environment variable, or raise if it has no value.

    Missing configuration must stop the process at startup. Returning None
    would let the program run on and fail somewhere unrelated, much later.
    """
    value = os.environ.get(name, default)
    if value is None:
        raise ImproperlyConfigured(
            'Missing required environment variable: ' + name
            + '. See .env.example for the full list.'
        )
    return value


def env_bool(name, default='0'):
    """Read a flag. Anything other than 1/true/yes/on is False.

    Never use bool() on an environment variable: every non-empty string is
    truthy, so bool('False') and bool('0') are both True.
    """
    return env(name, default).strip().lower() in {'1', 'true', 'yes', 'on'}


def env_list(name, default=''):
    """Read a comma-separated list, dropping blanks and stray whitespace."""
    return [item.strip() for item in env(name, default).split(',') if item.strip()]


